    #[test]
    fn opening_old_index_does_not_certify_semantic_provenance() {
        use crate::api::search_engine::{ensure_semantic_projection, SearchEngine, TextStorage};
        let directory = tempfile::TempDir::new().unwrap();
        let mut engine = SearchEngine::new(directory.path().to_str().unwrap());
        let config = crate::semantic_keys::next_production_chunking();
        assert!(ensure_semantic_projection(directory.path(), &config).is_ok());
        engine
            .add_text_book_placed(
                "ספר בדיקה".into(),
                "/בדיקה".into(),
                "book.txt".into(),
                0,
                0,
                "תוכן הספר הארוך דיו לבדיקת מטא נתונים".into(),
                None,
                TextStorage::InIndex,
                None,
            )
            .unwrap();
        engine.commit().unwrap();
        drop(engine);
        std::fs::remove_file(directory.path().join("otzaria_index_meta.json")).unwrap();
        let engine = SearchEngine::new(directory.path().to_str().unwrap());
        assert!(ensure_semantic_projection(directory.path(), &config).is_err());
        drop(engine);
        if let Ok(bytes) = std::fs::read_to_string(directory.path().join("otzaria_index_meta.json"))
        {
            let meta: serde_json::Value = serde_json::from_str(&bytes).unwrap();
            assert_eq!(meta["semantic_projection_version"], 0);
        }
    }

