    #[test]
    fn issue34_crossline_nested_notes_survive_index_storage_in_both_memory_modes() {
        use crate::api::search_engine::{semantic_texts, SearchEngine, TextStatus, TextStorage};
        use tantivy::schema::Value as _;
        let raw = "ראש🙂 <i class='footnote'>חיצון לפני <i class='footnote'>פנימי ראשון\nפנימי שני<sup>12</sup> זנב פנימי</i> חיצון אחרי</i> סוף\nתורה<sup>12</sup> והלכה למעשה בשורה ללא הערות גוף";
        let expected = [
            ("ראש🙂", vec!["חיצון לפני", "פנימי ראשון"]),
            ("סוף", vec!["חיצון אחרי", "פנימי שני זנב פנימי"]),
            ("תורה והלכה למעשה בשורה ללא הערות גוף", vec![]),
        ];
        for economy in [false, true] {
            let directory = tempfile::TempDir::new().unwrap();
            let mut engine = SearchEngine::new(directory.path().to_str().unwrap());
            engine.set_economy_indexing(economy).unwrap();
            engine
                .add_text_book_placed(
                    "ספר הערות".into(),
                    "/בדיקה".into(),
                    "nested.txt".into(),
                    0,
                    0,
                    raw.to_string(),
                    None,
                    TextStorage::InIndex,
                    None,
                )
                .unwrap();
            engine.commit().unwrap();
            drop(engine);
            let index = tantivy::Index::open_in_dir(directory.path()).unwrap();
            let reader = index.reader().unwrap();
            let searcher = reader.searcher();
            let mut documents = Vec::new();
            for (segment_ord, segment) in searcher.segment_readers().iter().enumerate() {
                let ids = segment.fast_fields().u64("id").unwrap();
                for doc_id in 0..segment.max_doc() {
                    let address = tantivy::DocAddress::new(segment_ord as u32, doc_id);
                    documents.push((
                        ids.first(doc_id).unwrap(),
                        address,
                        crate::doc_store::load_document(&searcher, address).unwrap(),
                    ));
                }
            }
            documents.sort_unstable_by_key(|(id, _, _)| *id);
            let documents: Vec<_> = documents
                .into_iter()
                .map(|(_, address, document)| (address, document))
                .collect();
            assert_eq!(documents.len(), 3, "economy={economy}");
            let projected = semantic_texts(&searcher, &documents, true).unwrap();
            for (line, (main, notes)) in projected.iter().zip(&expected) {
                assert_eq!(line.status, TextStatus::Ok);
                assert_eq!(&line.text, main, "economy={economy}");
                assert_eq!(&line.semantic_notes, notes, "economy={economy}");
            }
            let lexical = semantic_texts(&searcher, &documents, false).unwrap();
            for (line, source) in lexical.iter().zip(raw.split('\n')) {
                assert_eq!(
                    line.text,
                    crate::hebrew_query::normalize_text_for_indexing(source),
                    "lexical source text changed, economy={economy}"
                );
            }
            let note_field = index.schema().get_field(crate::note_spans::FIELD).unwrap();
            let metadata = documents[2]
                .1
                .get_first(note_field)
                .and_then(|value| value.as_str())
                .expect("classless-only semantic metadata must survive indexing");
            let serialized: serde_json::Value = serde_json::from_str(metadata).unwrap();
            assert!(serialized["semantic_nested"].is_object());
            assert!(serialized["plain"]["spans"].as_array().unwrap().is_empty());
            let display = crate::note_spans::NoteSpans::decode(Some(metadata))
                .display(lexical[2].text.clone(), false);
            assert_eq!(&*display, lexical[2].text);
            assert!(
                display.spans.is_empty(),
                "classless markers must not gain lexical display spans"
            );
        }
    }

